// Generates synthetic but realistic, mathematically consistent OHLCV candles
export function generateCandleHistory(basePrice: number, days = 60, volatility = 0.018): Candle[] {
  const candles: Candle[] = [];
  let currentPrice = basePrice * (1 - days * 0.0015);
  const now = new Date();

  for (let i = days; i >= 0; i--) {
    const date = new Date(now.getTime() - i * 24 * 60 * 60 * 1000);
    // skip weekends
    const dayOfWeek = date.getDay();
    if (dayOfWeek === 0 || dayOfWeek === 6) continue;

    const drift = (Math.random() - 0.48) * volatility * currentPrice;
    const open = currentPrice;
    const close = Math.max(1, open + drift);
    const high = Math.max(open, close) + Math.random() * volatility * currentPrice * 0.8;
    const low = Math.min(open, close) - Math.random() * volatility * currentPrice * 0.8;
    const volume = Math.floor(Math.random() * 8000000 + 4000000);

    candles.push({
      time: date.toISOString().split('T')[0],
      timestamp: date.getTime(),
      open: Number(open.toFixed(2)),
      high: Number(high.toFixed(2)),
      low: Number(low.toFixed(2)),
      close: Number(close.toFixed(2)),
      volume,
    });

    currentPrice = close;
  }

  // Ensure last candle closes near basePrice
  if (candles.length > 0) {
    const last = candles[candles.length - 1];
    last.close = basePrice;
    last.high = Math.max(last.high, basePrice);
    last.low = Math.min(last.low, basePrice);
  }

  return candles;
}

